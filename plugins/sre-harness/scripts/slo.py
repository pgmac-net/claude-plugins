from sre_common import SiteError, guarded, load_site, load_yaml, schema_errors

SLO_SUFFIX = ".slo.yaml"
SLO_NAME = re.compile(r"^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$")
SELECTOR = re.compile(r"^[a-zA-Z_:][a-zA-Z0-9_:]*(\{[^{}`$\\]*\})?$")
DURATION = re.compile(r"^([1-9][0-9]*)([smhd])$")
SECONDS = {"s": 1, "m": 60, "h": 3600, "d": 86400}
BASE_WINDOW = "5m"
SHORT_WINDOWS = ("1h", "6h", "1d")
# Multi-window burn-rate thresholds (Google SRE workbook), used to call a budget "burning fast".
FAST_BURN = {"1h": 14.4, "6h": 6.0}
DEFAULT_NAMESPACE = "sre-harness"
RULES_HEADER = "# Generated by sre-harness slo.py generate. Do not edit; change the .slo.yaml files instead.\n"
QUERY_TIMEOUT = 30


@dataclass
class Slo:  # pylint: disable=too-many-instance-attributes
    """One SLO, as the harness understands it."""

    name: str
    service: str
    journey: str
    target: float
    window: str
    counter: bool
    good: str
    total: str
    budget: bool
    interval: int | None
    path: str


@dataclass
class Journey:
    name: str
    service: str
    meta: dict[str, Any]
    path: str


@dataclass
class Findings:
    errors: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    slos: list[Slo] = field(default_factory=list)
    journeys: list[Journey] = field(default_factory=list)


def seconds(duration: str) -> int:
    match = DURATION.fullmatch(duration)
    if not match:
        raise ValueError(f"not a duration: {duration}")
    return int(match.group(1)) * SECONDS[match.group(2)]


def front_matter(text: str) -> dict[str, Any] | None:
    """The YAML between a leading '---' line and the next one, or None."""
    if not text.startswith("---\n"):
        return None
    end = text.find("\n---", 4)
    if end < 0:
        return None
    loaded = yaml.safe_load(text[4:end])
    return loaded if isinstance(loaded, dict) else None


def _slo_from(doc: dict[str, Any], rel: str) -> Slo:
    spec = doc["spec"]
    ratio = spec["indicator"]["spec"]["ratioMetric"]
    notes = doc["metadata"]["annotations"]
    interval = notes.get("sre-harness/expected-interval")
    return Slo(
        name=doc["metadata"]["name"],
        service=spec["service"],
        journey=notes["sre-harness/journey"],
        target=float(spec["objectives"][0]["target"]),
        window=spec["timeWindow"][0]["duration"],
        counter=bool(ratio["counter"]),
        good=ratio["good"]["metricSource"]["spec"]["query"].strip(),
        total=ratio["total"]["metricSource"]["spec"]["query"].strip(),
        budget=notes.get("sre-harness/budget", "true") == "true",
        interval=seconds(interval) if interval else None,
        path=rel,
    )


def _slo_problems(slo: Slo, retention_days: int) -> list[str]:
    problems = []
    for which, query in (("good", slo.good), ("total", slo.total)):
        if not SELECTOR.fullmatch(query):
            problems.append(f"{which} query must be a plain selector, metric{{labels}}; the harness adds the functions")
    if seconds(slo.window) > retention_days * 86400:
        problems.append(f"window {slo.window} is longer than the backend keeps data ({retention_days} days)")
    if seconds(slo.window) < seconds("1d"):
        problems.append("window must be at least 1d")
    if not slo.counter and slo.interval is None:
        problems.append("a gauge indicator (counter: false) needs the sre-harness/expected-interval annotation")
    if slo.interval is not None and not 10 <= slo.interval <= 300:
        problems.append("expected-interval must be between 10s and 5m")
    return problems


def _load_journey(path: Path, site_root: Path, known_refs: set[str] | None, found: Findings) -> None:
    rel = path.relative_to(site_root).as_posix()
    meta = front_matter(path.read_text(encoding="utf-8"))
    if meta is None:
        found.errors.append(f"{rel}: no YAML front matter")
        return
    problems = schema_errors(meta, "journey.schema.json")
    if problems:
        found.errors.extend(f"{rel}: {msg}" for msg in problems)
        return
    if meta["service"] != f"component:{path.parent.name}":
        found.errors.append(f"{rel}: service {meta['service']} does not match its directory {path.parent.name}")
    if not (path.parent / meta["error_budget_policy"]).is_file():
        found.errors.append(f"{rel}: error_budget_policy {meta['error_budget_policy']} does not exist beside it")
    if known_refs is not None:
        refs = [
            meta["service"],
            *(ref for step in meta["steps"] for ref in step.get("depends_on", [])),
            *meta.get("suspends", []),
        ]
        found.errors.extend(f"{rel}: {ref} is not in the catalog" for ref in refs if ref not in known_refs)
    found.journeys.append(Journey(name=path.stem, service=meta["service"], meta=meta, path=rel))


def _load_slo(path: Path, site_root: Path, retention_days: int, found: Findings) -> None:
    """Needs the journeys loaded first: an SLO must name a journey that exists."""
    rel = path.relative_to(site_root).as_posix()
    try:
        slo_doc = load_yaml(path)
    except SiteError as exc:
        found.errors.append(str(exc))
        return
    problems = schema_errors(slo_doc, "openslo.schema.json")
    if problems:
        found.errors.extend(f"{rel}: {msg}" for msg in problems)
        return
    slo = _slo_from(slo_doc, rel)
    found.errors.extend(f"{rel}: {msg}" for msg in _slo_problems(slo, retention_days))
    if slo.service != path.parent.name:
        found.errors.append(f"{rel}: spec.service {slo.service} does not match its directory {path.parent.name}")
    if not any(j.service == f"component:{slo.service}" and j.name == slo.journey for j in found.journeys):
        found.errors.append(f"{rel}: journey {slo.journey} has no journey file in {path.parent.name}/")
    found.slos.append(slo)


def load(site_root: Path, doc: dict[str, Any], known_refs: set[str] | None = None) -> Findings:
    """Read and check every journey and SLO under the site's journeys path."""
    found = Findings()
    settings = doc.get("slo") or {}
    if not settings:
        return found
    try:
        root = inside(site_root, settings["journeys_path"])
    except SiteError as exc:
        found.errors.append(f"slo/journeys_path: {exc}")
        return found
    if not root.is_dir():
        found.errors.append(f"slo/journeys_path: {settings['journeys_path']} is not a directory")
        return found

    links = sorted(p for p in root.rglob("*") if p.is_symlink())
    found.errors.extend(
        f"{p.relative_to(site_root).as_posix()}: links are not allowed under journeys_path" for p in links
    )
    for path in sorted(root.rglob("*.md")):
        if path.name.startswith(("README", "error-budget-policy")) or path.parent == root or path.is_symlink():
            continue
        _load_journey(path, site_root, known_refs, found)
    for path in sorted(root.rglob(f"*{SLO_SUFFIX}")):
        if not path.is_symlink():
            _load_slo(path, site_root, settings["retention_days"], found)

    names = [slo.name for slo in found.slos]
    found.errors.extend(
        f"SLO name {name} is used more than once" for name in sorted({n for n in names if names.count(n) > 1})
    )
    measured = {(f"component:{slo.service}", slo.journey) for slo in found.slos}
    found.warnings.extend(
        f"{j.path}: no SLO measures this journey" for j in found.journeys if (j.service, j.name) not in measured
    )
    return found


def coverage(
    found: Findings, services: dict[str, int], tiers: dict[int, dict[str, Any]]
) -> tuple[list[str], dict[str, Any]]:
    """Warnings for services whose tier requires journeys but have none, and a summary."""
    with_journeys = {j.service for j in found.journeys}
    warnings, needing = [], 0
    for ref, tier in sorted(services.items()):
        if "journeys" in tiers.get(tier, {}).get("requires", []):
            needing += 1
            if ref not in with_journeys:
                warnings.append(f"{ref}: tier {tier} requires journeys and an SLO; it has none yet")
    return warnings, {
        "journeys": len(found.journeys),
        "slos": len(found.slos),
        "services_needing_journeys": needing,
        "services_with_journeys": needing - len(warnings),
    }


# --- recording rules ------------------------------------------------------------


def windows(slo: Slo) -> list[str]:
    """Windows recorded for an SLO: the short ones that fit inside its window, then the window itself."""
    found = [w for w in SHORT_WINDOWS if seconds(w) < seconds(slo.window)]
    return [*found, slo.window]


def error_ratio_5m(slo: Slo) -> str:
    """PromQL for the share of bad events over five minutes."""
    if slo.counter:
        total = f"sum(rate({slo.total}[{BASE_WINDOW}]))"
        return f"(1 - sum(rate({slo.good}[{BASE_WINDOW}])) / {total}) and on() ({total} > 0) or on() vector(0)"
    # The share of reported probes that failed. Scrape timing puts four or five one-minute
    # samples in a five-minute window, so counting samples against an expected number
    # would read jitter as failure. A prober silent for the whole window still counts as
    # failing: with no samples the expression is empty and 'or vector(1)' applies.
    return f"1 - avg(avg_over_time({slo.good}[{BASE_WINDOW}])) or on() vector(1)"


def rule_group(slo: Slo) -> dict[str, Any]:
    labels = {"slo": slo.name, "service": slo.service, "journey": slo.journey, "budget": str(slo.budget).lower()}
    selector = f'{{slo="{slo.name}"}}'
    rules: list[dict[str, Any]] = [
        {"record": f"slo:sli_error:ratio_rate{BASE_WINDOW}", "expr": error_ratio_5m(slo), "labels": dict(labels)}
    ]
    for window in windows(slo):
        rules.append(
            {
                "record": f"slo:sli_error:ratio_rate{window}",
                "expr": f"avg_over_time(slo:sli_error:ratio_rate{BASE_WINDOW}{selector}[{window}])",
                "labels": dict(labels),
            }
        )
    rules.append({"record": "slo:objective:ratio", "expr": f"vector({slo.target:g})", "labels": dict(labels)})
    rules.append(
        {
            "record": "slo:error_budget:remaining_ratio",
            "expr": f"1 - slo:sli_error:ratio_rate{slo.window}{selector} / {1 - slo.target:.6g}",
            "labels": dict(labels),
        }
    )
    return {"name": f"sre-harness-slo-{slo.name}", "interval": "1m", "rules": rules}


def render_rules(slos: list[Slo], namespace: str) -> str:
    """The rules file: one group per SLO, in the format mimirtool and Prometheus both read."""
    doc = {"namespace": namespace, "groups": [rule_group(slo) for slo in sorted(slos, key=lambda s: s.name)]}
    return RULES_HEADER + yaml.safe_dump(doc, sort_keys=False, width=200)


