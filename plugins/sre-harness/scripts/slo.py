TOKEN_SHAPE = re.compile(r"^[A-Za-z0-9_.:=+/-]{8,2048}$")
MAX_TOKEN_FILE = 4096


def token_dir(env: dict[str, str] | None = None) -> Path:
    """The only directory a token file is read from."""
    env = dict(os.environ) if env is None else env
    return Path(env.get("XDG_CONFIG_HOME") or Path.home() / ".config") / "sre-harness"


def read_token(settings: dict[str, Any], env: dict[str, str] | None = None) -> str:
    """The read token, from the named variable or from a file in the harness's config directory.

    The file must be a regular file (not a symlink) readable by its owner only,
    small, and shaped like a token: the token is sent to the backend, so this
    must not become a way to send some other file there.
    """
    env = dict(os.environ) if env is None else env
    if settings.get("token_env") and env.get(settings["token_env"]):
        token = env[settings["token_env"]].strip()
    elif settings.get("token_file"):
        token = _token_from_file(token_dir(env) / settings["token_file"])
    else:
        raise SiteError("no metrics read token: set the variable named by slo.token_env, or create slo.token_file")
    if not TOKEN_SHAPE.fullmatch(token):
        raise SiteError("the metrics read token is not a single token-shaped line")
    return token


def _token_from_file(path: Path) -> str:
    try:
        info = path.lstat()
    except OSError as exc:
        raise SiteError(f"no metrics read token file at {path}") from exc
    if not stat.S_ISREG(info.st_mode):
        raise SiteError(f"{path} must be a regular file, not a link or anything else")
    if info.st_mode & 0o077:
        raise SiteError(f"{path} must be readable by its owner only (chmod 600)")
    if info.st_size > MAX_TOKEN_FILE:
        raise SiteError(f"{path} is too large to be a token")
    return path.read_text(encoding="utf-8").strip()


class _NoRedirect(urllib.request.HTTPRedirectHandler):
    """Refuse redirects: the token must reach only the configured host."""

    def redirect_request(self, req, fp, code, msg, headers, newurl):  # noqa: PLR0913, PLR0917  pylint: disable=too-many-arguments,too-many-positional-arguments
        raise urllib.error.HTTPError(req.full_url, code, "redirect refused", headers, fp)


_OPENER = urllib.request.build_opener(_NoRedirect)


def query(settings: dict[str, Any], promql: str, token: str, at: float | None = None) -> list[dict[str, Any]]:
    """An instant query against the backend, now or at a Unix time.

    Raises SiteError with the backend's message, never the token.
    """
    params: dict[str, str] = {"query": promql}
    if at is not None:
        params["time"] = f"{at:.0f}"
    url = settings["url"].rstrip("/") + "/api/v1/query?" + urllib.parse.urlencode(params)
    request = urllib.request.Request(url)  # noqa: S310 - the URL is site configuration, https or localhost only
    if settings.get("user"):
        pair = base64.b64encode(f"{settings['user']}:{token}".encode()).decode()
        request.add_unredirected_header("Authorization", f"Basic {pair}")
    else:
        request.add_unredirected_header("Authorization", f"Bearer {token}")
    try:
        with _OPENER.open(request, timeout=QUERY_TIMEOUT) as response:
            body = json.loads(response.read().decode())
    except urllib.error.HTTPError as exc:
        raise SiteError(f"metrics backend answered HTTP {exc.code}") from exc
    except (urllib.error.URLError, TimeoutError, ValueError) as exc:
        raise SiteError(f"metrics backend could not be queried: {type(exc).__name__}") from exc
    if body.get("status") != "success":
        raise SiteError(f"metrics backend refused the query: {body.get('error', 'no reason given')}")
    return body["data"]["result"]


def assess(slo: Slo, values: dict[str, float]) -> dict[str, Any]:
    """Turn the recorded values for one SLO into attainment, budget and state."""
    window_error = values.get(f"slo:sli_error:ratio_rate{slo.window}")
    result: dict[str, Any] = {
        "slo": slo.name,
        "service": f"component:{slo.service}",
        "journey": slo.journey,
        "target": slo.target,
        "window": slo.window,
        "spends_budget": slo.budget,
    }
    if window_error is None:
        return {**result, "state": "unknown", "reason": "no recorded data yet; are the rules synced?"}
    allowed = 1 - slo.target
    burn = {
        w: round(values[f"slo:sli_error:ratio_rate{w}"] / allowed, 2)
        for w in FAST_BURN
        if f"slo:sli_error:ratio_rate{w}" in values
    }
    remaining = 1 - window_error / allowed
    result.update(
        {
            "attainment": round(1 - window_error, 6),
            "budget_remaining": round(remaining, 4),
            "budget_remaining_minutes": round(remaining * allowed * seconds(slo.window) / 60, 1),
            "burn_rate": burn,
        }
    )
    if not slo.budget:
        state = "informational"
    elif remaining <= 0:
        state = "exhausted"
    elif any(burn.get(w, 0) > limit for w, limit in FAST_BURN.items()):
        state = "burning fast"
    else:
        state = "healthy"
    return {**result, "state": state}


def freeze_scope(slo: Slo, journeys: list[Journey]) -> list[str]:
    """Services frozen, with Tier 2 off, while this SLO's budget is exhausted: its own, then its journey's suspends."""
    own = f"component:{slo.service}"
    extra = next((j.meta.get("suspends", []) for j in journeys if j.service == own and j.name == slo.journey), [])
    return [own, *(ref for ref in extra if ref != own)]


def with_freeze(result: dict[str, Any], scope: list[str]) -> dict[str, Any]:
    """Add the freeze to one SLO's status. Only a budgeted SLO can freeze anything."""
    if not result["spends_budget"]:
        return result
    return {**result, "frozen": result["state"] == "exhausted", "freeze_scope": scope}


def status(
    settings: dict[str, Any], slos: list[Slo], token: str, journeys: list[Journey] | None = None
) -> list[dict[str, Any]]:
    """One query for all SLOs; then the maths above, per SLO."""
    # SLO names are [a-z0-9-] by schema, so they need no regex escaping. Python's re.escape
    # would turn '-' into '\-', an invalid escape inside a PromQL string literal (HTTP 400).
    if any(not SLO_NAME.fullmatch(slo.name) for slo in slos):
        raise SiteError("an SLO name has characters the harness does not put into a query")
    names = "|".join(slo.name for slo in slos)
    rows = query(settings, f'{{__name__=~"slo:sli_error:ratio_rate.+", slo=~"{names}"}}', token) if slos else []
    values: dict[str, dict[str, float]] = {}
    for row in rows:
        metric = row["metric"]
        try:
            values.setdefault(metric["slo"], {})[metric["__name__"]] = float(row["value"][1])
        except (KeyError, ValueError, IndexError):
            continue
    journeys = journeys or []
    return [with_freeze(assess(slo, values.get(slo.name, {})), freeze_scope(slo, journeys)) for slo in slos]


# --- commands -----------------------------------------------------------------------


def _known_refs(site_root: Path, doc: dict[str, Any]) -> set[str]:
    import catalog_check  # noqa: PLC0415  pylint: disable=import-outside-toplevel

    report = catalog_check.CatalogReport()
    return {entity.ref for entity in catalog_check.load_entities(site_root / doc["catalog"]["path"], report)}


def inside(site_root: Path, relative: str) -> Path:
    """A path in the site repository. Refuses anything that resolves outside it, links included."""
    path = site_root / relative
    if not path.resolve().is_relative_to(site_root.resolve()):
        raise SiteError(f"{relative} resolves outside the site repository")
    return path


def _rules_path(site_root: Path, settings: dict[str, Any]) -> Path:
    path = inside(site_root, settings["rules_file"])
    if path.is_symlink():
        raise SiteError(f"{settings['rules_file']} is a link; the rules file must be a plain file")
    return path


def cmd_check(_args: argparse.Namespace, site_root: Path, doc: dict[str, Any]) -> int:
    found = load(site_root, doc, _known_refs(site_root, doc))
    print(
        json.dumps(
            {
                "ok": not found.errors,
                "errors": found.errors,
                "warnings": found.warnings,
                "journeys": len(found.journeys),
                "slos": len(found.slos),
            },
            indent=2,
        )
    )
    return 1 if found.errors else 0


def cmd_generate(args: argparse.Namespace, site_root: Path, doc: dict[str, Any]) -> int:
    settings = doc.get("slo") or {}
    if not settings:
        raise SiteError("site.yaml has no slo section")
    found = load(site_root, doc, _known_refs(site_root, doc))
    if found.errors:
        print(json.dumps({"ok": False, "errors": found.errors}, indent=2))
        return 1
    rendered = render_rules(found.slos, settings.get("rules_namespace", DEFAULT_NAMESPACE))
    path = _rules_path(site_root, settings)
    current = path.read_text(encoding="utf-8") if path.is_file() else None
    if args.check:
        if current != rendered:
            print(f"{settings['rules_file']} is stale; run: slo.py generate", file=sys.stderr)
            return 1
        print(f"{settings['rules_file']} is up to date")
        return 0
    if current != rendered:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(rendered, encoding="utf-8")
        print(f"wrote {settings['rules_file']} ({len(found.slos)} SLO(s))")
    else:
        print(f"{settings['rules_file']} unchanged")
    return 0


def cmd_dashboard(args: argparse.Namespace, site_root: Path, doc: dict[str, Any]) -> int:
    settings = doc.get("slo") or {}
    if not settings.get("dashboard_file"):
        raise SiteError("site.yaml has no slo.dashboard_file")
    found = load(site_root, doc, _known_refs(site_root, doc))
    if found.errors:
        print(json.dumps({"ok": False, "errors": found.errors}, indent=2))
        return 1
    import slo_dashboard  # noqa: PLC0415  pylint: disable=import-outside-toplevel

    rendered = slo_dashboard.render(found.slos)
    path = inside(site_root, settings["dashboard_file"])
    if path.is_symlink():
        raise SiteError(f"{settings['dashboard_file']} is a link; the dashboard file must be a plain file")
    current = path.read_text(encoding="utf-8") if path.is_file() else None
    if args.check:
        if current != rendered:
            print(f"{settings['dashboard_file']} is stale; run: slo.py dashboard", file=sys.stderr)
            return 1
        print(f"{settings['dashboard_file']} is up to date")
        return 0
    if current != rendered:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(rendered, encoding="utf-8")
        print(f"wrote {settings['dashboard_file']} ({len(found.slos)} SLO(s))")
    else:
        print(f"{settings['dashboard_file']} unchanged")
    return 0


def _valid(site_root: Path, doc: dict[str, Any]) -> tuple[dict[str, Any], Findings]:
    settings = doc.get("slo") or {}
    if not settings:
        raise SiteError("site.yaml has no slo section")
    found = load(site_root, doc)
    if found.errors:
        raise SiteError(f"journeys or SLOs are not valid ({len(found.errors)} problem(s)); run slo.py check")
    return settings, found


def _selected(args: argparse.Namespace, found: Findings) -> list[Slo]:
    return [
        slo
        for slo in found.slos
        if (not args.service or args.service in (f"component:{slo.service}", slo.service))
        and (not args.slo or slo.name == args.slo)
    ]


def cmd_status(args: argparse.Namespace, site_root: Path, doc: dict[str, Any]) -> int:
    settings, found = _valid(site_root, doc)
    print(
        json.dumps({"slos": status(settings, _selected(args, found), read_token(settings), found.journeys)}, indent=2)
    )
    return 0


def cmd_nagios(args: argparse.Namespace, site_root: Path, doc: dict[str, Any]) -> int:
    """A Nagios check. Any failure is UNKNOWN (3), never the CRITICAL that exit 2 would mean."""
    import budget  # noqa: PLC0415  pylint: disable=import-outside-toplevel

    try:
        settings, found = _valid(site_root, doc)
        code, line = budget.nagios(status(settings, _selected(args, found), read_token(settings), found.journeys))
    except SiteError as exc:
        code, line = budget.NAGIOS_CODES["UNKNOWN"], budget.ascii_text(f"SLO UNKNOWN - {exc}")
    print(line)
    return code


def cmd_snapshot(args: argparse.Namespace, site_root: Path, doc: dict[str, Any]) -> int:
    import budget  # noqa: PLC0415  pylint: disable=import-outside-toplevel

    settings, found = _valid(site_root, doc)
    history = Path(args.out)
    if not history.is_dir():
        raise SiteError(f"history directory {history} does not exist")
    today = date.fromisoformat(args.today) if args.today else None
    result = budget.snapshot(
        history, settings, found, read_token(settings), timezone=doc["incident"]["timezone"], today=today
    )
    print(json.dumps(result, indent=2))
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--site", help="site repository path")
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("check", help="validate journeys and SLOs").set_defaults(run=cmd_check)
    generate = sub.add_parser("generate", help="write the recording rules")
    generate.add_argument("--check", action="store_true", help="fail if the rules file is stale; write nothing")
    generate.set_defaults(run=cmd_generate)
    dashboard = sub.add_parser("dashboard", help="write the Grafana dashboard for every SLO")
    dashboard.add_argument("--check", action="store_true", help="fail if the dashboard file is stale; write nothing")
    dashboard.set_defaults(run=cmd_dashboard)
    stat = sub.add_parser("status", help="attainment, budget remaining and state per SLO")
    stat.add_argument("--service", help="only this service (name or component:<name>)")
    stat.add_argument("--slo", help="only this SLO")
    stat.set_defaults(run=cmd_status)
    check = sub.add_parser("nagios", help="a Nagios check: budget state as an exit code and one line")
    check.add_argument("--service", help="only this service (name or component:<name>)")
    check.add_argument("--slo", help="only this SLO")
    check.set_defaults(run=cmd_nagios)
    snap = sub.add_parser("snapshot", help="write daily budget snapshots, filling any missing day inside retention")
    snap.add_argument("--out", required=True, help="history directory, one YYYY-MM.jsonl file per month")
    snap.add_argument("--today", help="local date to treat as today (YYYY-MM-DD); for tests and reruns")
    snap.set_defaults(run=cmd_snapshot)
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)

    def action() -> int:
        site_root, doc = load_site(args.site)
        return args.run(args, site_root, doc)

    return guarded(action)


if __name__ == "__main__":
    sys.exit(main())
