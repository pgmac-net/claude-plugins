#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# dependencies = ["jsonschema>=4.21", "pyyaml>=6"]
# ///
"""Regenerate the generated layer of a site's catalog from its sources.

Reads the git checkouts named by ``catalog.sources`` in site.yaml and rewrites
``<catalog>/generated/`` wholesale. It never reads live systems and never
touches a file outside ``generated/``. The same inputs always produce the same
bytes, so ``git diff`` of the generated layer is the change log of the estate.

Modes:
  (default)     rewrite the generated layer
  --check       exit 1 if the generated layer differs from what the sources
                would produce now (the catalog is stale, or was edited by hand)
  --check-live  report differences between declared and running ArgoCD
                applications; read-only, needs kubectl

Exit codes: 0 ok, 1 --check found differences, 2 the site or a source could
not be read.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess  # noqa: S404 - fixed argv, no shell
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml
from sre_common import SITE_FILE, SiteError, load_yaml, resolve_site

API_VERSION = "backstage.io/v1alpha1"
GENERATED_DIR = "generated"
SOURCES_FILE = "sources.yaml"
HEADER = "# Generated by sre-harness catalog_sync.py from source '{source}'. Do not edit: changes are overwritten.\n"
ANNOTATION = "sre-harness/generated-by"


@dataclass
class Build:
    """Everything one sync run would write."""

    files: dict[str, str] = field(default_factory=dict)
    warnings: list[str] = field(default_factory=list)
    counts: dict[str, int] = field(default_factory=dict)


def slug(text: str) -> str:
    """Lower-case entity-name form of arbitrary text."""
    return re.sub(r"-+", "-", re.sub(r"[^a-z0-9]+", "-", text.lower())).strip("-")[:63].strip("-")


def short_host(name: str) -> str:
    """First DNS label, the key hosts are matched on across sources."""
    return name.split(".", 1)[0].lower()


def _git(checkout: Path, *args: str) -> str:
    git = shutil.which("git")
    if not git:
        return ""
    done = subprocess.run(  # noqa: S603 - fixed argv
        [git, "-C", str(checkout), *args], capture_output=True, text=True, check=False
    )
    return done.stdout.strip() if done.returncode == 0 else ""


def _last_line(text: str) -> str:
    lines = text.strip().splitlines()
    return lines[-1] if lines else "no output"


def source_commit(checkout: Path, rel_path: str) -> str:
    """Last commit that touched the source path. Stable while the path is unchanged."""
    return _git(checkout, "log", "-1", "--format=%H", "--", rel_path) or "unknown"


# --- ansible-inventory -------------------------------------------------------


def read_ansible_inventory(path: Path) -> tuple[dict[str, set[str]], list[str]]:
    """Parse an INI inventory into {host: groups}.

    Only host names, groups and group children are read. Variables on host
    lines and in ``:vars`` sections are ignored, and host_vars/group_vars are
    never opened: they can hold vault data that must not reach the catalog.
    """
    members: dict[str, set[str]] = {}
    children: dict[str, set[str]] = {}
    warnings: list[str] = []
    group, mode = "ungrouped", "hosts"
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = re.split(r"\s[#;]", f" {raw}", maxsplit=1)[0].strip() if raw.strip()[:1] not in "#;" else ""
        if not line:
            continue
        section = re.fullmatch(r"\[([^\]:]+)(?::(children|vars))?\]", line)
        if section:
            group, mode = section.group(1), section.group(2) or "hosts"
            members.setdefault(group, set())
            continue
        if mode == "vars":
            continue
        token = line.split()[0]
        if mode == "children":
            children.setdefault(group, set()).add(token)
        elif "[" in token:
            warnings.append(f"host range '{token}' in group '{group}' is not expanded; skipped")
        else:
            members.setdefault(group, set()).add(token)

    def hosts_of(name: str, seen: frozenset[str] = frozenset()) -> set[str]:
        if name in seen:
            return set()
        found = set(members.get(name, set()))
        for child in children.get(name, set()):
            found |= hosts_of(child, seen | {name})
        return found

    hosts: dict[str, set[str]] = {}
    for name in set(members) | set(children):
        for host in hosts_of(name):
            hosts.setdefault(host, set()).add(name)
    return hosts, warnings


def ansible_entities(source: dict[str, Any], path: Path, owner: str) -> tuple[list[dict[str, Any]], list[str]]:
    """One host Resource per inventory host."""
    hosts, warnings = read_ansible_inventory(path)
    options = source.get("options", {})
    skip_groups = set(options.get("exclude_groups", []))
    skip_hosts = set(options.get("exclude_hosts", []))
    entities, used = [], {}
    for host in sorted(hosts):
        if host in skip_hosts or hosts[host] & skip_groups:
            continue
        name = f"host-{slug(short_host(host))}"
        if name in used:
            name = f"host-{slug(host)}"
        used[name] = host
        entities.append(
            {
                "apiVersion": API_VERSION,
                "kind": "Resource",
                "metadata": {"name": name, "title": host, "annotations": {ANNOTATION: source["name"]}},
                "spec": {
                    "type": "host",
                    "owner": owner,
                    "sre": {"inventory_name": host, "groups": sorted(hosts[host] - {"ungrouped"})},
                },
            }
        )
    return entities, warnings


# --- argocd-applications -----------------------------------------------------


def _render_area(area: Path) -> tuple[str, str | None]:
    """Return the YAML of one directory: helm-rendered if it is a chart, raw files otherwise."""
    if (area / "Chart.yaml").is_file():
        helm = shutil.which("helm")
        if not helm:
            return "", "helm is not installed; chart not rendered"
        done = subprocess.run(  # noqa: S603 - fixed argv
            [helm, "template", "catalog-sync", str(area)], capture_output=True, text=True, check=False
        )
        if done.returncode != 0:
            return (
                "",
                f"helm template failed: {_last_line(done.stderr)}",
            )
        return done.stdout, None
    texts = [p.read_text(encoding="utf-8") for p in sorted(area.glob("*.y*ml"))]
    return "\n---\n".join(texts), None


def _app_sources(spec: dict[str, Any]) -> list[dict[str, str]]:
    found = []
    for src in [spec.get("source")] if spec.get("source") else spec.get("sources", []):
        entry = {"repo_url": str(src.get("repoURL", ""))}
        for key, out in (("chart", "chart"), ("path", "path"), ("targetRevision", "target_revision")):
            if src.get(key) not in (None, ""):
                entry[out] = str(src[key])
        found.append(entry)
    return found


def argocd_entities(source: dict[str, Any], path: Path, owner: str) -> tuple[list[dict[str, Any]], list[str]]:
    """One Resource per ArgoCD Application, plus one for the cluster they deploy to."""
    warnings: list[str] = []
    cluster = source.get("options", {}).get("cluster")
    cluster_ref = f"resource:cluster-{cluster}" if cluster else None
    entities: dict[str, dict[str, Any]] = {}
    areas = sorted(p for p in path.iterdir() if p.is_dir()) if path.is_dir() else []
    for area in areas:
        text, problem = _render_area(area)
        if problem:
            warnings.append(f"{area.name}: {problem}")
            continue
        try:
            docs = [d for d in yaml.safe_load_all(text) if isinstance(d, dict)]
        except yaml.YAMLError as exc:
            warnings.append(f"{area.name}: not parseable as YAML, skipped ({type(exc).__name__})")
            continue
        for doc in docs:
            if doc.get("kind") != "Application" or not str(doc.get("apiVersion", "")).startswith("argoproj.io/"):
                continue
            app = str(doc.get("metadata", {}).get("name", ""))
            spec = doc.get("spec", {}) or {}
            name = f"app-{slug(app)}"
            if not app or name in entities:
                warnings.append(f"{area.name}: application '{app}' is unnamed or declared twice; later one skipped")
                continue
            sre: dict[str, Any] = {
                "application": app,
                "area": area.name,
                "namespace": str((spec.get("destination") or {}).get("namespace", "")),
                "project": str(spec.get("project", "")),
                "automated_sync": bool((spec.get("syncPolicy") or {}).get("automated") is not None),
                "sources": _app_sources(spec),
            }
            if source.get("pattern"):
                sre["pattern"] = source["pattern"]
            entity_spec: dict[str, Any] = {"type": "argocd-application", "owner": owner}
            if cluster_ref:
                entity_spec["dependsOn"] = [cluster_ref]
            entity_spec["sre"] = sre
            entities[name] = {
                "apiVersion": API_VERSION,
                "kind": "Resource",
                "metadata": {"name": name, "title": app, "annotations": {ANNOTATION: source["name"]}},
                "spec": entity_spec,
            }
    result = [entities[name] for name in sorted(entities)]
    if cluster:
        result.append(
            {
                "apiVersion": API_VERSION,
                "kind": "Resource",
                "metadata": {
                    "name": f"cluster-{cluster}",
                    "title": cluster,
                    "annotations": {ANNOTATION: source["name"]},
                },
                "spec": {"type": "kubernetes-cluster", "owner": owner, "sre": {"applications": len(entities)}},
            }
        )
    return result, warnings


# --- nagios-objects ----------------------------------------------------------

_DEFINE = re.compile(r"define\s+(\w+)\s*\{(.*?)\}", re.DOTALL)


def read_nagios_objects(path: Path) -> dict[str, list[dict[str, str]]]:
    """Parse Nagios object files into {object type: [directives]}. Templates are dropped."""
    files = [path] if path.is_file() else sorted(path.rglob("*.cfg"))
    objects: dict[str, list[dict[str, str]]] = {}
    for cfg in files:
        text = "\n".join(
            line.split(";", 1)[0]
            for line in cfg.read_text(encoding="utf-8", errors="replace").splitlines()
            if not line.lstrip().startswith("#")
        )
        for kind, body in _DEFINE.findall(text):
            directives = {}
            for line in body.splitlines():
                parts = line.split(None, 1)
                if parts:
                    directives[parts[0]] = parts[1].strip() if len(parts) > 1 else ""
            if directives.get("register") != "0":
                objects.setdefault(kind, []).append(directives)
    return objects


def _csv(value: str | None) -> list[str]:
    return [item.strip() for item in (value or "").split(",") if item.strip()]


def _host_groups(hosts: dict[str, dict[str, str]], hostgroups: list[dict[str, str]]) -> dict[str, set[str]]:
    """Every group each host belongs to, directly, by membership list, or through a nested group."""
    groups = {name: set(_csv(host.get("hostgroups"))) for name, host in hosts.items()}
    nested: dict[str, set[str]] = {}
    for hostgroup in hostgroups:
        group = hostgroup.get("hostgroup_name", "")
        nested[group] = set(_csv(hostgroup.get("hostgroup_members")))
        members = _csv(hostgroup.get("members"))
        for name in hosts if "*" in members else [m for m in members if m in groups]:
            groups[name].add(group)
    changed = True
    while changed:  # a host in a nested group is also in every group that contains it
        changed = False
        for parent, kids in nested.items():
            for name in hosts:
                if parent not in groups[name] and groups[name] & kids:
                    groups[name].add(parent)
                    changed = True
    return groups


def _service_hosts(service: dict[str, str], groups: dict[str, set[str]]) -> set[str]:
    """Hosts one service definition applies to, honouring '*' and '!exclusions'."""
    wanted: set[str] = set()
    excluded: set[str] = set()
    for item in _csv(service.get("host_name")):
        if item == "*":
            wanted.update(groups)
        elif item.startswith("!"):
            excluded.add(item[1:])
        else:
            wanted.add(item)
    for item in _csv(service.get("hostgroup_name")):
        in_group = {name for name in groups if item.lstrip("!") in groups[name]}
        (excluded if item.startswith("!") else wanted).update(in_group)
    return (wanted - excluded) & set(groups)


def nagios_hosts(path: Path, skip_hosts: set[str]) -> dict[str, dict[str, Any]]:
    """Resolve every host's groups and the checks that apply to it.

    check_command is deliberately not recorded: it can carry credentials.
    """
    objects = read_nagios_objects(path)
    hosts = {
        h["host_name"]: h for h in objects.get("host", []) if h.get("host_name") and h["host_name"] not in skip_hosts
    }
    groups = _host_groups(hosts, objects.get("hostgroup", []))
    checks: dict[str, set[str]] = {name: set() for name in hosts}
    for service in objects.get("service", []):
        if service.get("service_description"):
            for name in _service_hosts(service, groups):
                checks[name].add(service["service_description"])

    resolved = {}
    for name, host in hosts.items():
        entry: dict[str, Any] = {"host": name}
        entry.update({key: host[key] for key in ("alias", "address", "notes_url") if host.get(key)})
        entry["hostgroups"] = sorted(groups[name])
        entry["parents"] = sorted(p for p in _csv(host.get("parents")) if p in hosts)
        entry["checks"] = sorted(checks[name])
        resolved[name] = entry
    return resolved


def merge_nagios(
    source: dict[str, Any], path: Path, owner: str, existing: list[dict[str, Any]]
) -> tuple[list[dict[str, Any]], list[str]]:
    """Attach monitoring facts to matching Resources; make a Resource for each unmatched host."""
    skip = set(source.get("options", {}).get("exclude_hosts", []))
    monitored = nagios_hosts(path, skip)
    by_key: dict[str, dict[str, Any]] = {}
    for entity in existing:
        sre = entity["spec"].get("sre", {})
        key = sre.get("application") or short_host(sre.get("inventory_name", ""))
        if key:
            by_key.setdefault(str(key).lower(), entity)

    owner_of: dict[str, dict[str, Any]] = {}
    created = []
    for name in sorted(monitored):
        target = by_key.get(short_host(name))
        if target is None:
            target = {
                "apiVersion": API_VERSION,
                "kind": "Resource",
                "metadata": {
                    "name": f"monitored-{slug(name)}",
                    "title": name,
                    "annotations": {ANNOTATION: source["name"]},
                },
                "spec": {"type": "monitored-host", "owner": owner, "sre": {}},
            }
            created.append(target)
        owner_of[name] = target

    for name, target in owner_of.items():
        facts = dict(monitored[name])
        parents = facts.pop("parents")
        target["spec"].setdefault("sre", {})["monitoring"] = {"source": source["name"], **facts}
        refs = {f"resource:{owner_of[p]['metadata']['name']}" for p in parents} - {
            f"resource:{target['metadata']['name']}"
        }
        if refs:
            spec = target["spec"]
            merged = sorted(set(spec.get("dependsOn", [])) | refs)
            # Rebuild so dependsOn keeps its place before the sre block.
            target["spec"] = {
                "type": spec["type"],
                "owner": spec["owner"],
                "dependsOn": merged,
                **{k: v for k, v in spec.items() if k not in ("type", "owner", "dependsOn")},
            }
    return created, []


# --- build, write, check -----------------------------------------------------


def _checkout(site_root: Path, doc: dict[str, Any], source: dict[str, Any]) -> Path:
    repo = doc["repos"].get(source["repo"])
    if repo is None:
        raise SiteError(f"catalog source '{source['name']}': repo alias '{source['repo']}' is not in repos")
    if source["repo"] == "catalog":
        return site_root
    if not repo.get("path"):
        raise SiteError(f"catalog source '{source['name']}': repos/{source['repo']} has no local path")
    checkout = Path(repo["path"]).expanduser()
    if not checkout.is_dir():
        raise SiteError(f"catalog source '{source['name']}': checkout not found: {repo['path']}")
    return checkout


def _dump(entity: dict[str, Any], source: str) -> str:
    body = yaml.safe_dump(entity, sort_keys=False, default_flow_style=False, allow_unicode=True, width=100)
    return HEADER.format(source=source) + body


def build(site_root: Path, doc: dict[str, Any]) -> Build:
    """Compute the whole generated layer in memory."""
    result = Build()
    catalog = doc["catalog"]
    owner = catalog["default_owner"]
    sources = catalog.get("sources", [])
    per_source: dict[str, list[dict[str, Any]]] = {}
    meta: dict[str, dict[str, str]] = {}
    ordered = [s for s in sources if s["type"] != "nagios-objects"] + [
        s for s in sources if s["type"] == "nagios-objects"
    ]

    for source in ordered:
        checkout = _checkout(site_root, doc, source)
        path = checkout / source["path"]
        if not path.exists():
            raise SiteError(f"catalog source '{source['name']}': {source['path']} not found in {checkout}")
        if _git(checkout, "status", "--porcelain", "--", source["path"]):
            result.warnings.append(f"{source['name']}: uncommitted changes under {source['path']} are included")
        if source["type"] == "ansible-inventory":
            entities, warnings = ansible_entities(source, path, owner)
        elif source["type"] == "argocd-applications":
            entities, warnings = argocd_entities(source, path, owner)
        else:
            flat = [entity for group in per_source.values() for entity in group]
            entities, warnings = merge_nagios(source, path, owner, flat)
        per_source[source["name"]] = entities
        result.warnings.extend(f"{source['name']}: {w}" for w in warnings)
        meta[source["name"]] = {
            "type": source["type"],
            "repo": source["repo"],
            "path": source["path"],
            "commit": source_commit(checkout, source["path"]),
        }

    seen: dict[str, str] = {}
    for source_name in sorted(per_source):
        for entity in per_source[source_name]:
            name = entity["metadata"]["name"]
            if name in seen:
                result.warnings.append(f"{source_name}: entity name '{name}' already produced by {seen[name]}; skipped")
                continue
            seen[name] = source_name
            result.files[f"{source_name}/{name}.yaml"] = _dump(entity, source_name)
        result.counts[source_name] = sum(1 for path in result.files if path.startswith(f"{source_name}/"))
    result.files[SOURCES_FILE] = HEADER.format(source="site.yaml") + yaml.safe_dump(
        {"sources": {name: meta[name] for name in sorted(meta)}}, sort_keys=False
    )
    return result


def read_generated(generated: Path) -> dict[str, str]:
    """Current contents of the generated layer, keyed by relative path."""
    if not generated.is_dir():
        return {}
    return {
        path.relative_to(generated).as_posix(): path.read_text(encoding="utf-8")
        for path in sorted(generated.rglob("*"))
        if path.is_file()
    }


def differences(wanted: dict[str, str], current: dict[str, str]) -> list[str]:
    """Human-readable list of how the generated layer differs from a fresh build."""
    found = [f"missing: {path}" for path in sorted(set(wanted) - set(current))]
    found += [f"unexpected: {path}" for path in sorted(set(current) - set(wanted))]
    found += [f"changed: {path}" for path in sorted(set(wanted) & set(current)) if wanted[path] != current[path]]
    return found


def write_generated(generated: Path, files: dict[str, str]) -> None:
    """Replace the generated layer with exactly these files."""
    if generated.exists():
        shutil.rmtree(generated)
    for rel, text in files.items():
        target = generated / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")


def live_report(doc: dict[str, Any], wanted: dict[str, str]) -> tuple[list[str], list[str]]:
    """Compare declared ArgoCD applications with the ones running. Read-only."""
    lines, problems = [], []
    kubectl = shutil.which("kubectl")
    for source in doc["catalog"].get("sources", []):
        if source["type"] != "argocd-applications":
            continue
        context = source.get("options", {}).get("kube_context")
        if not context:
            problems.append(f"{source['name']}: no options.kube_context; skipped")
            continue
        if not kubectl:
            problems.append(f"{source['name']}: kubectl is not installed")
            continue
        done = subprocess.run(  # noqa: S603 - fixed argv, read-only verb
            [
                kubectl,
                "--context",
                context,
                "--request-timeout=20s",
                "get",
                "applications.argoproj.io",
                "-A",
                "-o",
                "json",
            ],
            capture_output=True,
            text=True,
            check=False,
        )
        if done.returncode != 0:
            problems.append(f"{source['name']}: kubectl failed: {_last_line(done.stderr)}")
            continue
        running = {item["metadata"]["name"] for item in json.loads(done.stdout).get("items", [])}
        declared = set()
        for rel, text in wanted.items():
            if rel.startswith(f"{source['name']}/app-"):
                declared.add(yaml.safe_load(text)["spec"]["sre"]["application"])
        lines += [f"{source['name']}: declared but not running: {name}" for name in sorted(declared - running)]
        lines += [f"{source['name']}: running but not declared: {name}" for name in sorted(running - declared)]
        lines.append(f"{source['name']}: {len(declared & running)} application(s) declared and running")
    return lines, problems


def main(argv: list[str] | None = None) -> int:
    """Command-line entry point."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--site", help="site repository path (default: SRE_HARNESS_SITE, then ~/.config/sre-harness/site)"
    )
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="exit 1 if the generated layer is stale or hand-edited")
    mode.add_argument("--check-live", action="store_true", help="compare declared and running ArgoCD applications")
    args = parser.parse_args(argv)

    try:
        site_root = resolve_site(args.site)
        doc = load_yaml(site_root / SITE_FILE)
        if not isinstance(doc, dict) or not isinstance(doc.get("catalog"), dict):
            raise SiteError("site.yaml has no catalog section; run validate_site.py")
        result = build(site_root, doc)
    except (SiteError, KeyError) as exc:
        print(f"ERROR {exc}", file=sys.stderr)
        return 2

    generated = site_root / doc["catalog"]["path"] / GENERATED_DIR
    for warning in result.warnings:
        print(f"WARNING {warning}")

    if args.check_live:
        lines, problems = live_report(doc, result.files)
        for line in lines:
            print(line)
        for problem in problems:
            print(f"WARNING {problem}")
        return 0

    found = differences(result.files, read_generated(generated))
    if args.check:
        for line in found:
            print(line)
        print(
            "generated layer is current"
            if not found
            else f"generated layer is stale: {len(found)} difference(s); run catalog_sync.py"
        )
        return 1 if found else 0

    write_generated(generated, result.files)
    for name in sorted(result.counts):
        print(f"{name}: {result.counts[name]} entit{'y' if result.counts[name] == 1 else 'ies'}")
    print(f"wrote {len(result.files)} file(s) to {generated}; {len(found)} changed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
